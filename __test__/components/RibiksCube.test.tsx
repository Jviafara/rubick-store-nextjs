import RubiksCube from '@/components/RubiksCube'
import { render, screen } from '@testing-library/react'

jest.mock('@/components/HeroHeading', () => ({
  __esModule: true,
  default: () => <div data-testid='hero-heading' />,
  HeroHeading: () => <div data-testid='hero-heading' />,
}))

jest.mock('@/components/Cube', () => ({
  __esModule: true,
  default: () => <div data-testid='cube' />,
  Cube: () => <div data-testid='cube' />,
}))

jest.mock('@react-three/fiber', () => ({
  Canvas: () => (
    <div data-testid='three-canvas'>
      <div data-testid='cube' />
    </div>
  ),
  useFrame: jest.fn(),
  useThree: jest.fn(),
}))

jest.mock('@react-three/drei', () => ({
  Environment: () => null,
  OrbitControls: () => null,
}))

jest.mock('@/components/HeroFeatureRow', () => ({
  __esModule: true,
  default: () => <div data-testid='hero-feature-row' />,
  HeroFeatureRow: () => <div data-testid='hero-feature-row' />,
}))

describe('RubiksCube', () => {
  it('renders the heading', () => {
    render(<RubiksCube />)

    expect(screen.getByTestId('hero-heading')).toBeInTheDocument()
  })

  it('renders the 3D canvas', () => {
    render(<RubiksCube />)

    expect(screen.getByTestId('three-canvas')).toBeInTheDocument()
  })

  it('renders the 3D canvas', () => {
    render(<RubiksCube />)

    expect(screen.getByTestId('cube')).toBeInTheDocument()
  })

  it('Left/Above Panel', () => {
    render(<RubiksCube />)

    expect(screen.getByText(/cube status/i)).toBeVisible()

    const resetButton = screen.getByText(/reset experience/i)
    expect(resetButton).toBeVisible()
    expect(resetButton).toBeEnabled()
  })

  it('render scramble Panel', () => {
    render(<RubiksCube />)

    const title = screen
      .getAllByRole('heading')
      .find(heading => heading.textContent?.trim().toLowerCase() === 'scramble')

    expect(title).toBeVisible()

    const scrambleButton = screen.getByText(/scramble cube/i)
    expect(scrambleButton).toBeVisible()
  })

  it('render solution Panel', () => {
    render(<RubiksCube />)

    expect(screen.getByText(/Generated by CubeJS/i)).toBeVisible()

    const solveButton = screen.getByText(/solve cube/i)
    expect(solveButton).toBeVisible()
  })

  it('renders the Feature Row', () => {
    render(<RubiksCube />)

    expect(screen.getByTestId('hero-feature-row')).toBeInTheDocument()
  })
})
